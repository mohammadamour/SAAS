<script setup>
import { ref, computed } from 'vue';
import { useIntelStore } from '../stores/useIntelStore';
import { 
  Zap, 
  FileText, 
  Check, 
  Database, 
  Activity, 
  Sparkles 
} from 'lucide-vue-next';

const store = useIntelStore();
const copiedMarkdown = ref(false);

const dossier = computed(() => store.dossier.value);

const cacheTelemetryText = computed(() => {
  if (!dossier.value) return 'STANDBY // READY FOR TELEMETRY';
  if (dossier.value.cached) {
    return `SERVED FROM REDIS BUFFER (${dossier.value.processing_time_ms}ms) · 0 LLM TOKENS BURNED`;
  }
  return `LIVE INGESTION COMPLETED (${dossier.value.processing_time_ms}ms) · 4 STREAMS SYNCHRONIZED`;
});

function exportMarkdownDossier() {
  if (!dossier.value || !navigator.clipboard) return;

  const d = dossier.value;
  const md = `# PRISM // OS — Executive Intelligence Brief
**Target**: ${d.brand?.name || d.domain} (${d.domain})  
**Acquired**: ${new Date(d.timestamp * 1000).toUTCString()}  
**Cache Status**: ${d.cached ? 'Redis In-Memory Buffer' : 'Fresh Multi-Stream Probe'} (${d.processing_time_ms}ms)

---

## 1. Brand & Digital Footprint
- **Display Name**: ${d.brand?.name}
- **Primary Brand Color**: \`${d.brand?.primary_color}\`
- **Secondary Brand Color**: \`${d.brand?.secondary_color}\`
- **Overview**: ${d.brand?.description}

## 2. Cloud Infrastructure & Security Telemetry
- **Cloud Host**: ${d.network?.cloud_host}
- **Resolved IP**: \`${d.network?.ip_address}\`
- **Measured TTFB Latency**: ${d.network?.ttfb_ms} ms
- **SSL / TLS Version**: ${d.network?.tls_version} (${d.network?.ssl_valid ? 'Valid' : 'Expired'} - ${d.network?.ssl_days_left} days left)
- **Edge Server**: \`${d.network?.server_header}\`

## 3. Web Performance & Core Vitals (Lighthouse)
- **Performance**: ${d.vitals?.performance_score}/100
- **SEO Audit**: ${d.vitals?.seo_score}/100
- **Accessibility**: ${d.vitals?.accessibility_score}/100
- **First Contentful Paint**: ${d.vitals?.fcp_seconds}s
- **Speed Index**: ${d.vitals?.speed_index}s

## 4. AI Strategic Teardown
> "${d.ai_dossier?.brutal_truth}"

- **Competitive Moat**: ${d.ai_dossier?.moat}
- **Existential Vulnerability**: ${d.ai_dossier?.vulnerability}
- **Top Competitors**: ${d.ai_dossier?.top_competitors?.join(', ')}
- **Inferred Tech Stack**: ${d.ai_dossier?.estimated_tech_stack?.join(', ')}

---
*Generated by PRISM // OS — Autonomous Corporate & Infrastructure Intelligence Terminal*
`;

  navigator.clipboard.writeText(md);
  copiedMarkdown.value = true;
  setTimeout(() => {
    copiedMarkdown.value = false;
  }, 2200);
}
</script>

<template>
  <footer class="prism-status-bar">
    <!-- Left: Redis & Execution Telemetry Status -->
    <div class="telemetry-info font-mono">
      <div class="status-indicator">
        <Zap :size="14" :class="dossier?.cached ? 'text-emerald' : 'text-accent'" />
        <span class="telemetry-text" :class="{ 'text-cached': dossier?.cached }">
          {{ cacheTelemetryText }}
        </span>
      </div>
    </div>

    <!-- Right: Export Dossier Action -->
    <div class="actions-right">
      <button
        type="button"
        class="export-btn font-mono"
        @click="exportMarkdownDossier"
        title="Copy complete 4-pillar intelligence brief formatted in Markdown"
      >
        <template v-if="copiedMarkdown">
          <Check :size="14" class="text-emerald" />
          <span class="text-emerald">COPIED DOSSIER (MD)</span>
        </template>
        <template v-else>
          <FileText :size="14" class="text-accent" />
          <span>EXPORT EXECUTIVE DOSSIER</span>
        </template>
      </button>
    </div>
  </footer>
</template>

